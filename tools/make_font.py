"""Builds src/vita/menu_font.h: printable ASCII (32..126) as 8-bit coverage bitmaps for the settings menu (settings.c),
from Pillow's bundled font (Aileron Regular, public domain / CC0). One fixed cell height, each glyph its own width.
   py tools/make_font.py [size]"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

size = int(sys.argv[1]) if len(sys.argv) > 1 else 22
font = ImageFont.load_default(size=size)
asc, desc = font.getmetrics()
h = asc + desc
glyphs = []
for ch in range(32, 127):
    w = max(1, round(font.getlength(chr(ch))))
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((0, 0), chr(ch), font=font, fill=255)
    glyphs.append((w, img.tobytes()))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "vita", "menu_font.h")
with open(out, "w", newline="\n") as f:
    f.write("/* generated by tools/make_font.py from Aileron Regular (public domain): ASCII 32..126, 8-bit coverage */\n")
    f.write("#define MENU_FONT_H %d\n" % h)
    f.write("static const unsigned char menu_font_w[95] = {%s};\n" % ",".join(str(w) for w, _ in glyphs))
    offs, o = [], 0
    for w, _ in glyphs:
        offs.append(o)
        o += w * h
    f.write("static const unsigned menu_font_off[95] = {%s};\n" % ",".join(map(str, offs)))
    data = b"".join(px for _, px in glyphs)
    f.write("static const unsigned char menu_font_px[%d] = {\n" % len(data))
    for i in range(0, len(data), 40):
        f.write(",".join(str(b) for b in data[i:i + 40]) + ",\n")
    f.write("};\n")
print(out, "cell height", h, "bytes", len(data))
