"""Writes src/vita/com_gen.c: the method lists (vtable order, stack bytes popped) of the COM interfaces the game uses,
from llvm-mingw's d3d9.h, dsound.h and dinput.h. The Vita build makes every game-visible COM object a guest vtable
of shim slots built from these (com.c); methods without a C implementation are survey stubs returning S_OK.
Every argument is 4 bytes in these interfaces, plus 4 for `this`.
usage: py tools/recomp/gen_com.py"""
import glob
import os
import re

INC = glob.glob(os.path.expandvars(r'%LOCALAPPDATA%\Microsoft\WinGet\Packages\MartinStorsjo.LLVM-MinGW*\llvm-mingw-*\include'))[0]
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'vita', 'com_gen.c')
WANT = {
    'd3d9.h': None,  # all of them
    'dsound.h': {'IDirectSound8', 'IDirectSoundBuffer8', 'IDirectSoundBuffer', 'IDirectSound3DBuffer',
                 'IDirectSound3DListener', 'IDirectSound', 'IDirectSoundNotify'},
    'dinput.h': {'IDirectInput8A', 'IDirectInputDevice8A', 'IDirectInputEffect'},
}

ifaces = {}
for hdr, want in WANT.items():
    text = open(os.path.join(INC, hdr), errors='replace').read()
    for m in re.finditer(r'#define INTERFACE (\w+)\s*\n\s*DECLARE_INTERFACE\w*\((.*?)\n\};', text, re.S):
        name, body = m.group(1), m.group(2)
        if (want is not None and name not in want) or name in ifaces:
            continue
        methods = []
        for mm in re.finditer(r'STDMETHOD_?\((?:[^,()]+,\s*)?(\w+)\)\s*\((THIS_?)([^;]*?)\)\s*PURE;', body, re.S):
            args = mm.group(3).strip()
            n = 0 if mm.group(2) == 'THIS' or not args else args.count(',') + 1
            methods.append((mm.group(1), 4 + 4 * n))
        if methods:
            ifaces[name] = methods

with open(OUT, 'w') as f:
    f.write('/* generated by tools/recomp/gen_com.py from llvm-mingw headers: COM method lists and stack bytes popped */\n')
    f.write('#include "com.h"\n\n')
    for name, methods in sorted(ifaces.items()):
        f.write('static const ComMethod m_%s[] = {%s};\n' % (name, ', '.join('{"%s", %d}' % m for m in methods)))
    f.write('\nconst ComIface g_ifaces[] = {\n')
    for name, methods in sorted(ifaces.items()):
        f.write('    {"%s", m_%s, %d},\n' % (name, name, len(methods)))
    f.write('    {NULL, NULL, 0},\n};\n')
print('%d interfaces: %s' % (len(ifaces), ' '.join('%s(%d)' % (n, len(m)) for n, m in sorted(ifaces.items()))))
