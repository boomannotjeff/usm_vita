"""Writes src/vita/imports_gen.c: every import of USM.exe with the stack bytes it pops on return (stdcall
arguments; 0 for cdecl). The Vita build binds each import to a C shim; an import without one still needs the
right pop so it can be stubbed (return 0) without wrecking the guest stack.
stdcall sizes come from llvm-mingw's i686 import libraries (`_HeapAlloc@12`); MSVCR71 is cdecl; binkw32 names
carry their own decoration; MSVC thiscall members (msvcp71) pop their arguments, read from the mangled name.
usage: py tools/recomp/gen_imports.py [USM.exe]"""
import glob
import os
import re
import struct
import subprocess
import sys

EXE = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('USM_EXE', 'USM.exe')
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'vita', 'imports_gen.c')
MINGW = glob.glob(os.path.expandvars(r'%LOCALAPPDATA%\Microsoft\WinGet\Packages\MartinStorsjo.LLVM-MinGW*\llvm-mingw-*'))[0]


def imports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    n = struct.unpack_from('<H', d, pe + 6)[0]
    opt = struct.unpack_from('<H', d, pe + 20)[0]
    secs = [struct.unpack_from('<IIII', d, pe + 24 + opt + 40 * i + 8) for i in range(n)]

    def off(rva):
        for vs, va, rs, ro in secs:
            if va <= rva < va + max(vs, rs):
                return rva - va + ro

    def cstr(o):
        return d[o:d.index(b'\0', o)].decode()

    k = off(struct.unpack_from('<I', d, pe + 24 + 104)[0])
    while True:
        oft, _, _, name, ft = struct.unpack_from('<IIIII', d, k)
        if not name:
            break
        dll = cstr(off(name))
        t = off(oft or ft)
        while True:
            v = struct.unpack_from('<I', d, t)[0]
            if not v:
                break
            yield dll, ('#%d' % (v & 0xffff)) if v & 0x80000000 else cstr(off(v) + 2)
            t += 4
        k += 20


stdcall = {}
for lib in glob.glob(os.path.join(MINGW, 'i686-w64-mingw32', 'lib', 'lib*.a')):
    out = subprocess.run([os.path.join(MINGW, 'bin', 'llvm-nm'), lib], capture_output=True, text=True).stdout
    for m in re.finditer(r' T _(\w+)@(\d+)$', out, re.M):
        stdcall.setdefault(m.group(1), int(m.group(2)))

# MSVC mangled thiscall member: arguments after the return type, each a pointer/reference (4) or int-sized (4)
def msvc_thiscall(name):
    if 'QAE' not in name and 'IAE' not in name:
        return 0
    args = name.split('AE', 1)[1][1:]  # skip the return type ('@' for constructors)
    if args.startswith('X'):
        return 0
    return 4 * len(re.findall(r'P[AB][A-Z]|A[AB]V[^@]*@+|A[AB][A-Z]|[C-KMN]', args.rsplit('@Z', 1)[0]))


rows, unknown = [], []
for dll, name in imports(EXE):
    low = dll.lower()
    if low.startswith('msvcr'):
        pops = 0
    elif low.startswith('msvcp'):
        pops = msvc_thiscall(name)
    elif '@' in name and name.startswith('_'):  # binkw32: _BinkOpen@8
        pops = int(name.rsplit('@', 1)[1])
    elif name in stdcall:
        pops = stdcall[name]
    else:
        pops = -1
        unknown.append('%s!%s' % (dll, name))
    rows.append((dll, name, pops))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as f:
    f.write('/* generated by tools/recomp/gen_imports.py: USM.exe imports and the stack bytes each pops (-1: unknown) */\n')
    f.write('#include "vita.h"\n\nconst ImportInfo g_imports[] = {\n')
    for dll, name, pops in rows:
        f.write('    {"%s", "%s", %d},\n' % (dll, name, pops))
    f.write('};\nconst unsigned g_nimports = %d;\n' % len(rows))
print('%d imports, %d with unknown argument size: %s' % (len(rows), len(unknown), ' '.join(unknown)))
