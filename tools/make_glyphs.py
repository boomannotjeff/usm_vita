"""Draws the PlayStation button icons the tutorial prompts show (in the style of the PS2 version: a dark disc with
   the coloured symbol, L/R as grey keys) into src/vita/glyphs.h, a 256x32 RGBA atlas of 8 slots:
   0 cross, 1 circle, 2 square, 3 triangle, 4 L, 5 R. gl.c draws font glyphs that point at it (native.c f_7791a0).
   py tools/make_glyphs.py"""
import os
from PIL import Image, ImageDraw, ImageFont

S, K = 32, 4             # slot size, supersampling
B = S * K
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "vita", "glyphs.h")
font = ImageFont.truetype("arialbd.ttf", int(B * 0.62))


def disc(draw):
    draw.ellipse((2 * K, 2 * K, B - 2 * K, B - 2 * K), fill=(18, 18, 20, 255))         # dark rim
    draw.ellipse((4 * K, 4 * K, B - 4 * K, B - 4 * K), fill=(66, 66, 72, 255))         # grey face


def icon(k):
    im = Image.new("RGBA", (B, B), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    c, w = B / 2, int(2.6 * K)
    if k < 4:
        disc(d)
        r = B * 0.22
        if k == 0:    # cross, blue
            col = (124, 178, 232, 255)
            d.line((c - r, c - r, c + r, c + r), fill=col, width=w)
            d.line((c - r, c + r, c + r, c - r), fill=col, width=w)
        elif k == 1:  # circle, red
            d.ellipse((c - r, c - r, c + r, c + r), outline=(255, 102, 102, 255), width=w)
        elif k == 2:  # square, pink
            d.rectangle((c - r * 0.9, c - r * 0.9, c + r * 0.9, c + r * 0.9), outline=(232, 143, 208, 255), width=w)
        else:         # triangle, green
            p = [(c, c - r * 1.05), (c + r * 1.1, c + r * 0.8), (c - r * 1.1, c + r * 0.8)]
            d.line(p + [p[0], p[1]], fill=(64, 224, 176, 255), width=w, joint="curve")
    else:             # L / R key
        d.rounded_rectangle((2 * K, 5 * K, B - 2 * K, B - 5 * K), radius=6 * K, fill=(18, 18, 20, 255))
        d.rounded_rectangle((4 * K, 7 * K, B - 4 * K, B - 7 * K), radius=5 * K, fill=(86, 86, 94, 255))
        d.text((c, c), "L" if k == 4 else "R", font=font, fill=(255, 255, 255, 255), anchor="mm")
    return im.resize((S, S), Image.LANCZOS)


atlas = Image.new("RGBA", (S * 8, S), (0, 0, 0, 0))
for k in range(6):
    atlas.paste(icon(k), (k * S, 0))
px = atlas.tobytes()
assert len(px) == S * 8 * S * 4
with open(out, "w") as f:
    f.write("/* generated by tools/make_glyphs.py: PlayStation button icons, %dx%d RGBA, 8 slots of %d px */\n" % (S * 8, S, S))
    f.write("#define GLYPHS_W %d\n#define GLYPHS_H %d\nstatic const unsigned char g_glyphs_rgba[] = {\n" % (S * 8, S))
    for i in range(0, len(px), 32):
        f.write("".join("%d," % b for b in px[i:i + 32]) + "\n")
    f.write("};\n")
print("wrote", out)
